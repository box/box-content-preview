import React from 'react';
import noop from 'lodash/noop';
import { IconToggleButton } from '@box/blueprint-web';
import { ClosedCaption } from '@box/blueprint-web-assets/icons/Medium';
import MediaToggle from './MediaToggle';
import ToggleTooltipV2 from '../tooltip/ToggleTooltipV2';
import { stopActivationKeyPropagation } from './utils';
import { Subtitle } from './MediaSettingsMenuSubtitles';
import './SubtitlesToggle.scss';

export type Props = {
    isAutoGeneratedSubtitles?: boolean;
    isBlueprintEnabled?: boolean;
    isShowingSubtitles?: boolean;
    onSubtitlesToggle?: (isShowingSubtitles: boolean) => void;
    subtitles?: Array<Subtitle>;
};

export default function SubtitlesToggle({
    isAutoGeneratedSubtitles,
    isBlueprintEnabled = false,
    isShowingSubtitles,
    onSubtitlesToggle = noop,
    subtitles = [],
}: Props): JSX.Element | null {
    if (!subtitles.length) {
        return null;
    }

    const title = isAutoGeneratedSubtitles ? __('media_auto_generated_captions') : __('media_subtitles_cc');

    if (isBlueprintEnabled) {
        return (
            <ToggleTooltipV2 content={title}>
                <IconToggleButton
                    aria-label={title}
                    className="bp-SubtitlesToggleV2"
                    data-resin-target="subtitlesToggle"
                    data-target-id="SubtitlesToggle-toggle"
                    data-testid="bp-media-cc-button"
                    icon={ClosedCaption}
                    onKeyDown={stopActivationKeyPropagation}
                    onPressedChange={onSubtitlesToggle}
                    pressed={!!isShowingSubtitles}
                />
            </ToggleTooltipV2>
        );
    }

    return (
        <MediaToggle
            aria-pressed={isShowingSubtitles}
            className="bp-SubtitlesToggle"
            data-resin-target="subtitlesToggle"
            data-testid="bp-media-cc-button"
            onClick={(): void => onSubtitlesToggle(!isShowingSubtitles)}
            title={title}
        >
            <div className="bp-SubtitlesToggle-text">CC</div>
        </MediaToggle>
    );
}
