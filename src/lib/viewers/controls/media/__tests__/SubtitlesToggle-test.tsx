import React from 'react';
import { render, screen } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import BlueprintProviders from '../../../../BlueprintProviders';
import SubtitlesToggle from '../SubtitlesToggle';
import subtitles from '../__mocks__/subtitles';

describe('SubtitlesToggle', () => {
    const getWrapper = (props = {}) =>
        render(<SubtitlesToggle isShowingSubtitles onSubtitlesToggle={jest.fn()} subtitles={subtitles} {...props} />);

    const getToggle = async () => screen.findByTestId('bp-media-cc-button');

    describe('event handlers', () => {
        test('should toggle isShowingSubtitles when clicked', async () => {
            const onSubtitlesToggle = jest.fn();
            getWrapper({ isShowingSubtitles: false, onSubtitlesToggle });
            const toggle = await getToggle();

            await userEvent.click(toggle);

            expect(onSubtitlesToggle).toHaveBeenCalledWith(true);
        });
    });

    describe('render', () => {
        test('should return a valid wrapper', async () => {
            getWrapper();
            const toggle = await getToggle();

            expect(toggle).toBeInTheDocument();
        });

        test('should return null if no subtitles are passed in', () => {
            getWrapper({ subtitles: [] });
            const toggle = screen.queryByTestId('bp-media-cc-button');

            expect(toggle).toBeNull();
        });

        test.each([true, false])(
            'should set the aria-pressed attribute correspondingly when isShowingSubtitles is %s',
            async isShowingSubtitles => {
                getWrapper({ isShowingSubtitles });
                const toggle = await getToggle();

                if (isShowingSubtitles) {
                    expect(toggle).toHaveAttribute('aria-pressed', 'true');
                } else {
                    expect(toggle).toHaveAttribute('aria-pressed', 'false');
                }
            },
        );

        test.each`
            isAutoGeneratedSubtitles | title
            ${true}                  | ${__('media_auto_generated_captions')}
            ${false}                 | ${__('media_subtitles_cc')}
        `(
            'should set the title accordingly when isAutoGeneratedSubtitles is $isAutoGeneratedSubtitles',
            async ({ isAutoGeneratedSubtitles, title }) => {
                getWrapper({ isAutoGeneratedSubtitles, title });
                const toggle = await screen.findByTitle(title);

                expect(toggle).toBeInTheDocument();
            },
        );
    });

    describe('with Blueprint enabled', () => {
        const getBlueprintWrapper = (props = {}) =>
            render(
                <SubtitlesToggle
                    isBlueprintEnabled
                    isShowingSubtitles
                    onSubtitlesToggle={jest.fn()}
                    subtitles={subtitles}
                    {...props}
                />,
                { wrapper: BlueprintProviders },
            );

        test('should render a Blueprint toggle button instead of the legacy CC text', async () => {
            getBlueprintWrapper();
            const toggle = await getToggle();

            expect(toggle).toHaveClass('bp-SubtitlesToggleV2');
            expect(toggle).toHaveAttribute('data-resin-target', 'subtitlesToggle');
            expect(toggle).toHaveAttribute('data-target-id', 'SubtitlesToggle-toggle');
            expect(toggle.querySelector('svg')).toBeInTheDocument();
            expect(screen.queryByText('CC')).toBeNull();
        });

        test('should return null if no subtitles are passed in', () => {
            getBlueprintWrapper({ subtitles: [] });

            expect(screen.queryByTestId('bp-media-cc-button')).toBeNull();
        });

        test.each([true, false])('should set aria-pressed when isShowingSubtitles is %s', async isShowingSubtitles => {
            getBlueprintWrapper({ isShowingSubtitles });
            const toggle = await getToggle();

            expect(toggle).toHaveAttribute('aria-pressed', `${isShowingSubtitles}`);
        });

        test.each([true, false])(
            'should call onSubtitlesToggle with %s when clicked from the opposite state',
            async nextIsShowingSubtitles => {
                const onSubtitlesToggle = jest.fn();
                getBlueprintWrapper({ isShowingSubtitles: !nextIsShowingSubtitles, onSubtitlesToggle });

                await userEvent.click(await getToggle());

                expect(onSubtitlesToggle).toHaveBeenCalledWith(nextIsShowingSubtitles);
            },
        );

        test.each`
            isAutoGeneratedSubtitles | label
            ${true}                  | ${__('media_auto_generated_captions')}
            ${false}                 | ${__('media_subtitles_cc')}
        `(
            'should label the toggle accordingly when isAutoGeneratedSubtitles is $isAutoGeneratedSubtitles',
            async ({ isAutoGeneratedSubtitles, label }) => {
                getBlueprintWrapper({ isAutoGeneratedSubtitles });

                expect(await screen.findByRole('button', { name: label })).toBeInTheDocument();
            },
        );

        test.each(['{Enter}', ' '])('should stop %s from reaching the viewer shortcuts', async key => {
            const user = userEvent.setup();
            const documentKeydown = jest.fn();
            getBlueprintWrapper();

            await user.tab();
            expect(await getToggle()).toHaveFocus();

            document.addEventListener('keydown', documentKeydown);
            await user.keyboard(key);
            document.removeEventListener('keydown', documentKeydown);

            expect(documentKeydown).not.toHaveBeenCalled();
        });
    });
});
